# Builds src/fonts.css: the app's fonts as small embedded WOFF subsets, so it works fully offline
# (packaged desktop/tablet apps have no guaranteed network). Needs fontTools. Run: python3 fonts/make-fonts.py
import base64, io, sys
from fontTools import subset
from fontTools.ttLib import TTFont

LATIN = "U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+02C6,U+02DA,U+02DC,U+2013-2014,U+2018-201E,U+2022,U+2026,U+2032-2033,U+2039-203A,U+20AC,U+2122,U+2190-2193,U+2212,U+00D7,U+266D-266F,U+25B6,U+2318,U+2325,U+21E7,U+232B,U+2195,U+2194"
MUSIC = "U+1D11E-1D126,U+266D-266F"
SRC = [
  ('Inter', 400, '/usr/share/fonts/opentype/inter/Inter-Regular.otf', LATIN),
  ('Inter', 500, '/usr/share/fonts/opentype/inter/Inter-Medium.otf', LATIN),
  ('Inter', 600, '/usr/share/fonts/opentype/inter/Inter-SemiBold.otf', LATIN),
  ('Inter', 700, '/usr/share/fonts/opentype/inter/Inter-Bold.otf', LATIN),
  ('JetBrains Mono', 500, '/mnt/skills/examples/canvas-design/canvas-fonts/JetBrainsMono-Regular.ttf', LATIN),
  ('JetBrains Mono', 600, '/mnt/skills/examples/canvas-design/canvas-fonts/JetBrainsMono-Bold.ttf', LATIN),
  ('DAW Music', 400, '/usr/share/fonts/truetype/freefont/FreeSerif.ttf', MUSIC),
]

def uni(spec):
  out = []
  for part in spec.split(','):
    a = part[2:]
    if '-' in a: lo, hi = a.split('-'); out += range(int(lo, 16), int(hi, 16) + 1)
    else: out.append(int(a, 16))
  return out

css = ["/* Generated by fonts/make-fonts.py: Inter (OFL), JetBrains Mono (OFL), music glyphs from GNU FreeSerif (GPL + font exception). */"]
total = 0
for fam, w, path, spec in SRC:
  opts = subset.Options(); opts.flavor = 'woff'; opts.layout_features = ['kern', 'liga', 'tnum', 'calt']; opts.name_IDs = [1, 2]; opts.notdef_outline = True
  f = TTFont(path)
  s = subset.Subsetter(opts); s.populate(unicodes=uni(spec)); s.subset(f)
  buf = io.BytesIO(); f.flavor = 'woff'; f.save(buf)
  data = buf.getvalue(); total += len(data)
  css.append(f"@font-face {{ font-family: '{fam}'; font-weight: {w}; font-style: normal; font-display: swap; src: url(data:font/woff;base64,{base64.b64encode(data).decode()}) format('woff'); unicode-range: {spec}; }}")
open('src/fonts.css', 'w').write('\n'.join(css) + '\n')
print(f'src/fonts.css written, {total/1024:.0f} KB of fonts')
